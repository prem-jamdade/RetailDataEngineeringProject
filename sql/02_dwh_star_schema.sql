-- Schema: RETAIL_DW
-- Purpose: Star Schema Data Warehouse tables (Dimensions & Fact Sales)
--          with surrogate keys, foreign keys, constraints, and bitmap/B-tree indexes.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. DIM_DATE: Conformed Calendar Dimension (YYYYMMDD surrogate key)
-- -----------------------------------------------------------------------------
CREATE TABLE DIM_DATE (
    DATE_KEY        NUMBER(8) PRIMARY KEY,
    FULL_DATE       DATE NOT NULL UNIQUE,
    YEAR_NUM        NUMBER(4) NOT NULL,
    QUARTER_NUM     NUMBER(1) NOT NULL,
    QUARTER_NAME    VARCHAR2(10) NOT NULL,
    MONTH_NUM       NUMBER(2) NOT NULL,
    MONTH_NAME      VARCHAR2(20) NOT NULL,
    MONTH_SHORT     VARCHAR2(3) NOT NULL,
    YEAR_MONTH      VARCHAR2(7) NOT NULL,
    WEEK_OF_YEAR    NUMBER(2) NOT NULL,
    DAY_OF_MONTH    NUMBER(2) NOT NULL,
    DAY_OF_WEEK     NUMBER(1) NOT NULL,
    DAY_NAME        VARCHAR2(15) NOT NULL,
    IS_WEEKEND      CHAR(1) NOT NULL,
    CONSTRAINT CHK_DIM_DATE_WKND CHECK (IS_WEEKEND IN ('Y', 'N'))
);

-- -----------------------------------------------------------------------------
-- 2. DIM_STORE: Store Dimension (SCD Type 1 via MERGE)
-- -----------------------------------------------------------------------------
CREATE TABLE DIM_STORE (
    STORE_KEY       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STORE_CODE      VARCHAR2(30) NOT NULL UNIQUE,
    STORE_NAME      VARCHAR2(150) NOT NULL,
    CITY            VARCHAR2(100) NOT NULL,
    REGION          VARCHAR2(100) NOT NULL,
    STORE_CHANNEL   VARCHAR2(30) DEFAULT 'RETAIL' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- -----------------------------------------------------------------------------
-- 3. DIM_PRODUCT: Product Dimension (SCD Type 1 via MERGE)
-- -----------------------------------------------------------------------------
CREATE TABLE DIM_PRODUCT (
    PRODUCT_KEY         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_CODE        VARCHAR2(30) NOT NULL UNIQUE,
    PRODUCT_NAME        VARCHAR2(200) NOT NULL,
    CATEGORY            VARCHAR2(100) NOT NULL,
    SUBCATEGORY         VARCHAR2(100) NOT NULL,
    CURRENT_UNIT_COST   NUMBER(12, 2) NOT NULL,
    CURRENT_UNIT_PRICE  NUMBER(12, 2) NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_DIM_PROD_CAT ON DIM_PRODUCT(CATEGORY, SUBCATEGORY);

-- -----------------------------------------------------------------------------
-- 4. DIM_CUSTOMER: Customer Dimension (SCD Type 1 via MERGE)
-- -----------------------------------------------------------------------------
CREATE TABLE DIM_CUSTOMER (
    CUSTOMER_KEY        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_CODE       VARCHAR2(30) NOT NULL UNIQUE,
    CUSTOMER_NAME       VARCHAR2(150) NOT NULL,
    EMAIL               VARCHAR2(150),
    CUSTOMER_SEGMENT    VARCHAR2(50) NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_DIM_CUST_SEG ON DIM_CUSTOMER(CUSTOMER_SEGMENT);

-- -----------------------------------------------------------------------------
-- 5. FACT_SALES: Transaction-grain Fact Table
-- -----------------------------------------------------------------------------
CREATE TABLE FACT_SALES (
    SALES_KEY           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRANSACTION_ID      VARCHAR2(64) NOT NULL UNIQUE,
    DATE_KEY            NUMBER(8) NOT NULL,
    STORE_KEY           NUMBER NOT NULL,
    PRODUCT_KEY         NUMBER NOT NULL,
    CUSTOMER_KEY        NUMBER NOT NULL,
    SALE_TIMESTAMP      TIMESTAMP NOT NULL,
    QUANTITY            NUMBER(10, 0) NOT NULL,
    UNIT_COST           NUMBER(12, 2) NOT NULL,
    UNIT_PRICE          NUMBER(12, 2) NOT NULL,
    DISCOUNT_PCT        NUMBER(5, 2) DEFAULT 0 NOT NULL,
    GROSS_AMOUNT        NUMBER(14, 2) NOT NULL,
    DISCOUNT_AMOUNT     NUMBER(14, 2) NOT NULL,
    NET_AMOUNT          NUMBER(14, 2) NOT NULL,
    COST_AMOUNT         NUMBER(14, 2) NOT NULL,
    PROFIT_AMOUNT       NUMBER(14, 2) NOT NULL,
    PAYMENT_METHOD      VARCHAR2(50) NOT NULL,
    SOURCE_TYPE         VARCHAR2(20) NOT NULL,
    RECORD_HASH         VARCHAR2(64) NOT NULL,
    ETL_RUN_ID          NUMBER NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_FACT_DATE     FOREIGN KEY (DATE_KEY)     REFERENCES DIM_DATE(DATE_KEY),
    CONSTRAINT FK_FACT_STORE    FOREIGN KEY (STORE_KEY)    REFERENCES DIM_STORE(STORE_KEY),
    CONSTRAINT FK_FACT_PRODUCT  FOREIGN KEY (PRODUCT_KEY)  REFERENCES DIM_PRODUCT(PRODUCT_KEY),
    CONSTRAINT FK_FACT_CUSTOMER FOREIGN KEY (CUSTOMER_KEY) REFERENCES DIM_CUSTOMER(CUSTOMER_KEY),
    CONSTRAINT FK_FACT_RUN      FOREIGN KEY (ETL_RUN_ID)   REFERENCES ETL_PIPELINE_RUNS(RUN_ID)
);

CREATE INDEX IDX_FACT_DATE     ON FACT_SALES(DATE_KEY);
CREATE INDEX IDX_FACT_STORE    ON FACT_SALES(STORE_KEY);
CREATE INDEX IDX_FACT_PRODUCT  ON FACT_SALES(PRODUCT_KEY);
CREATE INDEX IDX_FACT_CUSTOMER ON FACT_SALES(CUSTOMER_KEY);
CREATE INDEX IDX_FACT_RUN      ON FACT_SALES(ETL_RUN_ID);
