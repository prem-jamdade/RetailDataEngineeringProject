-- =============================================================================
-- File: 01_staging_tables.sql
-- Schema: RETAIL_DW
-- Purpose: Create ETL Control, Watermark, Staging (Raw/Clean/Rejects), and
--          Source-to-Target Reconciliation tables in Oracle Database.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. ETL_PIPELINE_RUNS: Tracks every pipeline execution and row metrics
-- -----------------------------------------------------------------------------
CREATE TABLE ETL_PIPELINE_RUNS (
    RUN_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_UUID            VARCHAR2(64) NOT NULL UNIQUE,
    RUN_STARTED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RUN_FINISHED_AT     TIMESTAMP,
    STATUS              VARCHAR2(20) DEFAULT 'RUNNING' NOT NULL,
    SOURCE_CSV_FILES    NUMBER DEFAULT 0,
    SOURCE_API_BATCHES  NUMBER DEFAULT 0,
    RAW_ROW_COUNT       NUMBER DEFAULT 0,
    CLEAN_ROW_COUNT     NUMBER DEFAULT 0,
    REJECT_ROW_COUNT    NUMBER DEFAULT 0,
    DWH_INSERTED_COUNT  NUMBER DEFAULT 0,
    DWH_UPDATED_COUNT   NUMBER DEFAULT 0,
    ERROR_MESSAGE       VARCHAR2(4000),
    CONSTRAINT CHK_ETL_RUN_STATUS CHECK (STATUS IN ('RUNNING', 'SUCCESS', 'FAILED', 'PARTIAL'))
);

-- -----------------------------------------------------------------------------
-- 2. ETL_FILE_WATERMARK: Tracks processed files/API windows for incremental load
-- -----------------------------------------------------------------------------
CREATE TABLE ETL_FILE_WATERMARK (
    SOURCE_NAME         VARCHAR2(255) PRIMARY KEY,
    SOURCE_TYPE         VARCHAR2(20) NOT NULL,
    CONTENT_HASH        VARCHAR2(64) NOT NULL,
    ROW_COUNT           NUMBER DEFAULT 0 NOT NULL,
    LAST_RUN_ID         NUMBER NOT NULL,
    PROCESSED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_WM_RUN FOREIGN KEY (LAST_RUN_ID) REFERENCES ETL_PIPELINE_RUNS(RUN_ID),
    CONSTRAINT CHK_WM_SRC_TYPE CHECK (SOURCE_TYPE IN ('CSV', 'API'))
);

-- -----------------------------------------------------------------------------
-- 3. STG_SALES_RAW: Exact raw landing layer (all strings preserved for audit)
-- -----------------------------------------------------------------------------
CREATE TABLE STG_SALES_RAW (
    RAW_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID              NUMBER NOT NULL,
    SOURCE_TYPE         VARCHAR2(20) NOT NULL,
    SOURCE_FILE         VARCHAR2(255) NOT NULL,
    TRANSACTION_ID      VARCHAR2(100),
    SALE_TIMESTAMP_RAW  VARCHAR2(100),
    STORE_ID_RAW        VARCHAR2(50),
    STORE_NAME_RAW      VARCHAR2(150),
    STORE_CITY_RAW      VARCHAR2(100),
    STORE_REGION_RAW    VARCHAR2(100),
    CUSTOMER_ID_RAW     VARCHAR2(50),
    CUSTOMER_NAME_RAW   VARCHAR2(150),
    CUSTOMER_EMAIL_RAW  VARCHAR2(150),
    CUSTOMER_SEGMENT_RAW VARCHAR2(50),
    PRODUCT_ID_RAW      VARCHAR2(50),
    PRODUCT_NAME_RAW    VARCHAR2(200),
    CATEGORY_RAW        VARCHAR2(100),
    SUBCATEGORY_RAW     VARCHAR2(100),
    UNIT_COST_RAW       VARCHAR2(50),
    UNIT_PRICE_RAW      VARCHAR2(50),
    QUANTITY_RAW        VARCHAR2(50),
    DISCOUNT_PCT_RAW    VARCHAR2(50),
    PAYMENT_METHOD_RAW  VARCHAR2(50),
    INGESTED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RAW_RUN FOREIGN KEY (RUN_ID) REFERENCES ETL_PIPELINE_RUNS(RUN_ID)
);

CREATE INDEX IDX_STG_RAW_RUN ON STG_SALES_RAW(RUN_ID);

-- -----------------------------------------------------------------------------
-- 4. STG_SALES_CLEAN: Cleaned, typed, business-rule-validated staging records
-- -----------------------------------------------------------------------------
CREATE TABLE STG_SALES_CLEAN (
    CLEAN_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID              NUMBER NOT NULL,
    TRANSACTION_ID      VARCHAR2(64) NOT NULL,
    SALE_DATE           DATE NOT NULL,
    SALE_TIMESTAMP      TIMESTAMP NOT NULL,
    STORE_CODE          VARCHAR2(30) NOT NULL,
    STORE_NAME          VARCHAR2(150) NOT NULL,
    STORE_CITY          VARCHAR2(100) NOT NULL,
    STORE_REGION        VARCHAR2(100) NOT NULL,
    CUSTOMER_CODE       VARCHAR2(30) NOT NULL,
    CUSTOMER_NAME       VARCHAR2(150) NOT NULL,
    CUSTOMER_EMAIL      VARCHAR2(150),
    CUSTOMER_SEGMENT    VARCHAR2(50) NOT NULL,
    PRODUCT_CODE        VARCHAR2(30) NOT NULL,
    PRODUCT_NAME        VARCHAR2(200) NOT NULL,
    CATEGORY            VARCHAR2(100) NOT NULL,
    SUBCATEGORY         VARCHAR2(100) NOT NULL,
    UNIT_COST           NUMBER(12, 2) NOT NULL,
    UNIT_PRICE          NUMBER(12, 2) NOT NULL,
    QUANTITY            NUMBER(10, 0) NOT NULL,
    DISCOUNT_PCT        NUMBER(5, 2) DEFAULT 0 NOT NULL,
    GROSS_AMOUNT        NUMBER(14, 2) NOT NULL,
    DISCOUNT_AMOUNT     NUMBER(14, 2) NOT NULL,
    NET_AMOUNT          NUMBER(14, 2) NOT NULL,
    COST_AMOUNT         NUMBER(14, 2) NOT NULL,
    PROFIT_AMOUNT       NUMBER(14, 2) NOT NULL,
    PAYMENT_METHOD      VARCHAR2(50) NOT NULL,
    RECORD_HASH         VARCHAR2(64) NOT NULL,
    SOURCE_TYPE         VARCHAR2(20) NOT NULL,
    SOURCE_FILE         VARCHAR2(255) NOT NULL,
    PROCESSED_FLAG      CHAR(1) DEFAULT 'N' NOT NULL,
    LOADED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CLEAN_RUN FOREIGN KEY (RUN_ID) REFERENCES ETL_PIPELINE_RUNS(RUN_ID),
    CONSTRAINT CHK_CLEAN_PROC CHECK (PROCESSED_FLAG IN ('Y', 'N')),
    CONSTRAINT CHK_CLEAN_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_CLEAN_PRICE CHECK (UNIT_PRICE > 0 AND UNIT_COST >= 0)
);

CREATE INDEX IDX_STG_CLEAN_RUN_PROC ON STG_SALES_CLEAN(RUN_ID, PROCESSED_FLAG);
CREATE INDEX IDX_STG_CLEAN_TXN ON STG_SALES_CLEAN(TRANSACTION_ID);

-- -----------------------------------------------------------------------------
-- 5. STG_SALES_REJECTS: Invalid records quarantined with explicit rejection rules
-- -----------------------------------------------------------------------------
CREATE TABLE STG_SALES_REJECTS (
    REJECT_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID              NUMBER NOT NULL,
    SOURCE_TYPE         VARCHAR2(20) NOT NULL,
    SOURCE_FILE         VARCHAR2(255) NOT NULL,
    TRANSACTION_ID      VARCHAR2(100),
    RAW_PAYLOAD         CLOB,
    REJECTION_REASON    VARCHAR2(500) NOT NULL,
    REJECTED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_REJECT_RUN FOREIGN KEY (RUN_ID) REFERENCES ETL_PIPELINE_RUNS(RUN_ID)
);

CREATE INDEX IDX_STG_REJECTS_RUN ON STG_SALES_REJECTS(RUN_ID);

-- -----------------------------------------------------------------------------
-- 6. ETL_RECONCILIATION_LOG: Source-to-Target data quality & reconciliation log
-- -----------------------------------------------------------------------------
CREATE TABLE ETL_RECONCILIATION_LOG (
    RECON_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID              NUMBER NOT NULL,
    CHECK_NAME          VARCHAR2(100) NOT NULL,
    SOURCE_VALUE        NUMBER(18, 2),
    STAGING_VALUE       NUMBER(18, 2),
    DWH_VALUE           NUMBER(18, 2),
    VARIANCE            NUMBER(18, 2),
    STATUS              VARCHAR2(10) NOT NULL,
    DETAILS             VARCHAR2(1000),
    CHECKED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RECON_RUN FOREIGN KEY (RUN_ID) REFERENCES ETL_PIPELINE_RUNS(RUN_ID),
    CONSTRAINT CHK_RECON_STATUS CHECK (STATUS IN ('PASS', 'FAIL'))
);
